"use client";

import React, { useState } from "react";
import { ProjectBriefData } from "@/lib/types";
import { X, Copy, Check, Calendar, ArrowRight, FileText } from "lucide-react";

interface ProjectBriefModalProps {
  brief: ProjectBriefData;
  isOpen: boolean;
  onClose: () => void;
  onBookMeeting?: () => void;
}

export function ProjectBriefModal({ brief, isOpen, onClose, onBookMeeting }: ProjectBriefModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    const text = `PROJECT BRIEF: ${brief.projectName}
Objective: ${brief.objective}
Problem: ${brief.problem}
Target Users: ${brief.targetUsers}
Current Stage: ${brief.currentStage}
Target Timeline: ${brief.timeline}
Target Budget: ${brief.budget}

Proposed MVP Features:
${brief.proposedMVP.map((f) => `- ${f}`).join("\n")}

Potential Architecture:
${brief.potentialArchitecture.map((a) => `- ${a}`).join("\n")}

Open Questions:
${brief.openQuestions.map((q) => `- ${q}`).join("\n")}

Next Step: ${brief.nextStep}
Generated by Sora (Sorateq AI Assistant) on ${new Date(brief.generatedAt).toLocaleDateString()}`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-md p-4 sm:p-6 animate-fade-in">
      <div className="relative w-full max-w-2xl max-h-[90vh] bg-zinc-950 border border-white/15 rounded-2xl p-6 sm:p-8 flex flex-col shadow-2xl overflow-hidden">
        {/* Top Header */}
        <div className="flex items-center justify-between border-b border-white/10 pb-4">
          <div className="flex items-center space-x-2.5">
            <FileText className="w-4 h-4 text-emerald-400" />
            <span className="font-mono text-xs uppercase tracking-widest text-zinc-400">SORATEQ PROJECT BRIEF</span>
          </div>
          <button
            onClick={onClose}
            aria-label="Close brief modal"
            className="w-8 h-8 rounded-full flex items-center justify-center text-zinc-400 hover:text-white bg-zinc-900 border border-white/10 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Scrollable Content */}
        <div className="overflow-y-auto my-4 pr-1 space-y-6 text-sm">
          {/* Project Title */}
          <div>
            <span className="text-[10px] font-mono uppercase text-zinc-500">PROJECT INITIATIVE</span>
            <h2 className="text-xl font-semibold text-white mt-0.5">{brief.projectName}</h2>
            <p className="text-xs text-zinc-400 mt-1 leading-relaxed">{brief.objective}</p>
          </div>

          {/* Grid Meta */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5">
            <div className="bg-zinc-900/60 p-3 rounded-lg border border-white/5">
              <div className="text-[10px] font-mono uppercase text-zinc-500">Timeline</div>
              <div className="text-xs font-semibold text-zinc-200 mt-0.5">{brief.timeline}</div>
            </div>
            <div className="bg-zinc-900/60 p-3 rounded-lg border border-white/5">
              <div className="text-[10px] font-mono uppercase text-zinc-500">Stage</div>
              <div className="text-xs font-semibold text-zinc-200 mt-0.5">{brief.currentStage}</div>
            </div>
            <div className="bg-zinc-900/60 p-3 rounded-lg border border-white/5">
              <div className="text-[10px] font-mono uppercase text-zinc-500">Target Budget</div>
              <div className="text-xs font-semibold text-zinc-200 mt-0.5">{brief.budget}</div>
            </div>
            <div className="bg-zinc-900/60 p-3 rounded-lg border border-white/5">
              <div className="text-[10px] font-mono uppercase text-zinc-500">Users</div>
              <div className="text-xs font-semibold text-zinc-200 mt-0.5 truncate">{brief.targetUsers}</div>
            </div>
          </div>

          {/* Problem & Users */}
          <div className="space-y-2">
            <div className="text-xs font-mono uppercase text-zinc-400">Problem Statement</div>
            <div className="bg-zinc-900/40 p-3 rounded-lg border border-white/5 text-xs text-zinc-300 leading-relaxed">
              {brief.problem}
            </div>
          </div>

          {/* Proposed MVP */}
          <div className="space-y-2">
            <div className="text-xs font-mono uppercase text-zinc-400">Proposed MVP Scope (V1)</div>
            <ul className="space-y-1.5 bg-zinc-900/40 p-3 rounded-lg border border-white/5">
              {brief.proposedMVP.map((item, idx) => (
                <li key={idx} className="text-xs text-zinc-300 flex items-start">
                  <span className="text-emerald-400 mr-2 font-mono text-[10px]">0{idx + 1}.</span>
                  <span>{item}</span>
                </li>
              ))}
            </ul>
          </div>

          {/* Architecture */}
          <div className="space-y-2">
            <div className="text-xs font-mono uppercase text-zinc-400">Technical Architecture Direction</div>
            <div className="flex flex-wrap gap-2">
              {brief.potentialArchitecture.map((tech, idx) => (
                <span
                  key={idx}
                  className="text-xs font-mono px-2.5 py-1 rounded bg-zinc-900 text-zinc-300 border border-white/10"
                >
                  {tech}
                </span>
              ))}
            </div>
          </div>

          {/* Open Questions */}
          {brief.openQuestions && brief.openQuestions.length > 0 && (
            <div className="space-y-2">
              <div className="text-xs font-mono uppercase text-zinc-400">Key Questions for Discovery</div>
              <ul className="space-y-1 bg-zinc-900/40 p-3 rounded-lg border border-white/5">
                {brief.openQuestions.map((q, idx) => (
                  <li key={idx} className="text-xs text-zinc-400 flex items-center">
                    <span className="w-1.5 h-1.5 rounded-full bg-zinc-600 mr-2" />
                    <span>{q}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>

        {/* Bottom Actions */}
        <div className="border-t border-white/10 pt-4 flex flex-col sm:flex-row items-center justify-between gap-3">
          <button
            onClick={handleCopy}
            className="w-full sm:w-auto flex items-center justify-center space-x-2 text-xs font-mono px-4 py-2 rounded-lg border border-white/10 bg-zinc-900 text-zinc-300 hover:text-white hover:border-white/20 transition-all"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? "Copied to clipboard" : "Copy Brief Text"}</span>
          </button>

          {onBookMeeting && (
            <button
              onClick={() => {
                onClose();
                onBookMeeting();
              }}
              className="w-full sm:w-auto flex items-center justify-center space-x-2 text-xs font-medium px-5 py-2.5 rounded-lg bg-white text-zinc-950 hover:bg-zinc-200 transition-all shadow-md font-sans"
            >
              <Calendar className="w-3.5 h-3.5" />
              <span>Schedule Discovery Session</span>
              <ArrowRight className="w-3.5 h-3.5" />
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
